#!/usr/bin/env python3
"""Embed the bundled .lens prescriptions for the EffectCraft (WebAssembly) build.

EffectCraft plug-ins run sandboxed with no file access, so every builtin lens listed in
src/ae/builtin_lenses_generated.inc is compiled into the module as text. Comment and blank
lines are dropped and whitespace is collapsed; LensSystem::load_from_text() parses the rest
exactly like a .lens file on disk.

It also writes the Lens popup's options as ready-made JSON. EffectCraft meters every
instruction while it loads a plug-in, and escaping ~1400 labels at load time used nearly
all of that budget.

Usage: generate_ec_lens_bank.py <output.inc>
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
BUILTIN_INC = REPO_ROOT / "src" / "ae" / "builtin_lenses_generated.inc"

C_STRING = r'"((?:[^"\\]|\\.)*)"'
# {"id", "label", "relative/path.lens", manufacturer_index},
LENS_ENTRY = re.compile(rf"^\s*\{{{C_STRING}, {C_STRING}, {C_STRING}, (\d+)\}},\s*$")
# {"id", "label", first_lens_index, lens_count},
MANUFACTURER_ENTRY = re.compile(rf"^\s*\{{{C_STRING}, {C_STRING}, (\d+), (\d+)\}},\s*$")


def c_unescape(value: str) -> str:
    return value.replace('\\"', '"').replace("\\\\", "\\")


def c_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def compact_lens_text(text: str) -> str:
    lines = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        lines.append(" ".join(line.split()))
    return "\n".join(lines) + "\n"


def read_table(name: str, pattern: re.Pattern[str]) -> list[tuple[str, ...]]:
    rows: list[tuple[str, ...]] = []
    in_table = False
    for line in BUILTIN_INC.read_text(encoding="utf-8").splitlines():
        if line.startswith(f"constexpr ") and f" {name}[]" in line:
            in_table = True
            continue
        if in_table:
            if line.startswith("};"):
                break
            match = pattern.match(line)
            if match:
                rows.append(tuple(c_unescape(g) for g in match.groups()))
    return rows


def lens_popup_json(lenses: list[tuple[str, ...]], manufacturers: list[tuple[str, ...]]) -> str:
    # Must match ec_plugin.cpp: "Manufacturer / Lens", in builtin table order.
    labels = [f"{manufacturers[int(lens[3])][1]} / {lens[1]}" for lens in lenses]
    return ",".join(json.dumps(label, ensure_ascii=False) for label in labels)


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2

    out_path = Path(sys.argv[1])
    lenses = read_table("kBuiltinLenses", LENS_ENTRY)
    manufacturers = read_table("kBuiltinLensManufacturers", MANUFACTURER_ENTRY)
    paths = sorted({lens[2] for lens in lenses})
    if not paths or not manufacturers:
        print(f"no lenses found in {BUILTIN_INC}", file=sys.stderr)
        return 1

    out = [
        "// Generated by scripts/generate_ec_lens_bank.py; do not edit.",
        "",
        f"constexpr std::size_t kEcLensPopupOptionCount = {len(lenses)};",
        f'constexpr const char kEcLensPopupOptionsJson[] = "{c_string(lens_popup_json(lenses, manufacturers))}";',
        "",
        "constexpr EcLensText kEcLensTexts[] = {",
    ]
    for relative_path in paths:
        lens_file = REPO_ROOT / relative_path
        text = compact_lens_text(lens_file.read_text(encoding="utf-8", errors="replace"))
        escaped = c_string(text).replace("\n", "\\n")
        out.append(f'    {{"{c_string(relative_path)}", "{escaped}"}},')
    out.append("};")
    out.append("")

    new_content = "\n".join(out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    if not out_path.exists() or out_path.read_text(encoding="utf-8") != new_content:
        out_path.write_text(new_content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
